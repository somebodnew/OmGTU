# Лабораторная работа 8 — Вариант 21, Задание 7.2
# Краевая задача: y'' - (2/x)*y' - 0.4*y = 4x
# y'(0.6) = 0.6,  y'(0.9) = 1.5,  h = 0.1
#
# Общий вид: y'' + p(x)*y' + q(x)*y = f(x)
# p(x) = -2/x,  q(x) = -0.4,  f(x) = 4x
#
# Сетка: x1=0.6, x2=0.7, x3=0.8, x4=0.9  (4 узла, n=3 отрезка)
#
# Аппроксимация (метод конечных разностей):
#
#  k=1 (левое краевое, тип Неймана):
#    y'_1 ≈ (y2 - y1)/h = 0.6  =>  -y1 + y2 = 0.06
#    a1=0, b1=-1, c1=1, d1=0.06
#
#  k=2,3 (внутренние узлы):
#    y''_k ≈ (y_{k+1} - 2*y_k + y_{k-1}) / h^2
#    y'_k  ≈ (y_{k+1} - y_{k-1}) / (2h)
#    => (1/h^2 + p_k/(2h))*y_{k+1} + (-2/h^2 + q_k)*y_k + (1/h^2 - p_k/(2h))*y_{k-1} = f_k
#    a_k = 1/h^2 - p_k/(2h)
#    b_k = -2/h^2 + q_k
#    c_k = 1/h^2 + p_k/(2h)
#    d_k = f_k
#
#  k=4 (правое краевое, тип Неймана):
#    y'_4 ≈ (y4 - y3)/h = 1.5  =>  -y3 + y4 = 0.15
#    a4=-1, b4=1, c4=0, d4=0.15

def p(x): return -2.0 / x
def q(x): return -0.4
def f(x): return 4.0 * x

h  = 0.1
a  = 0.6   # левая граница
b  = 0.9   # правая граница
n  = round((b - a) / h)          # число отрезков = 3
N  = n + 1                        # число узлов = 4

# Узлы сетки
xs = [round(a + i * h, 10) for i in range(N)]

print("=" * 65)
print("  Краевая задача: y'' - (2/x)·y' - 0.4·y = 4x")
print("  y'(0.6) = 0.6,  y'(0.9) = 1.5,  h = 0.1")
print("=" * 65)
print(f"\nСетка: {[round(x, 2) for x in xs]}\n")

# ---------------------------------------------------------------
# Формирование СЛАУ: a_k * y_{k-1} + b_k * y_k + c_k * y_{k+1} = d_k
# Индексация: ak[0..N-1], bk[0..N-1], ck[0..N-1], dk[0..N-1]
# ---------------------------------------------------------------
ak = [0.0] * N
bk = [0.0] * N
ck = [0.0] * N
dk = [0.0] * N

# k=0  (x = 0.6): левое краевое  y'_1 = (y2-y1)/h = 0.6
ak[0] =  0.0
bk[0] = -1.0
ck[0] =  1.0
dk[0] =  0.6 * h   # = 0.06

# k=1,2 (внутренние узлы)
for k in range(1, N - 1):
    xk = xs[k]
    ak[k] = 1.0/h**2 - p(xk)/(2*h)
    bk[k] = -2.0/h**2 + q(xk)
    ck[k] = 1.0/h**2 + p(xk)/(2*h)
    dk[k] = f(xk)

# k=3  (x = 0.9): правое краевое  y'_4 = (y4-y3)/h = 1.5
ak[N-1] = -1.0
bk[N-1] =  1.0
ck[N-1] =  0.0
dk[N-1] =  1.5 * h  # = 0.15

# ---------------------------------------------------------------
# Вывод матрицы системы для наглядности
# ---------------------------------------------------------------
print("Матрица СЛАУ (коэффициенты a, b, c, d):")
print(f"  {'k':>3} | {'x_k':>6} | {'a_k':>10} | {'b_k':>10} | {'c_k':>10} | {'d_k':>10}")
print("  " + "-" * 59)
for k in range(N):
    print(f"  {k+1:>3} | {xs[k]:>6.2f} | {ak[k]:>10.4f} | {bk[k]:>10.4f} | {ck[k]:>10.4f} | {dk[k]:>10.4f}")

# ---------------------------------------------------------------
# Метод прогонки (алгоритм Томаса)
# Прямой ход: Uk = -ck / (ak*U_{k-1} + bk)
#             Vk = (dk - ak*V_{k-1}) / (ak*U_{k-1} + bk)
# Обратный ход: y_{N-1} = V_{N-1}
#               y_k = Uk*y_{k+1} + Vk
# ---------------------------------------------------------------
Uk = [0.0] * N
Vk = [0.0] * N

# k=0
Uk[0] = -ck[0] / bk[0]
Vk[0] =  dk[0] / bk[0]

print(f"\nПрямой ход прогонки:")
print(f"  {'k':>3} | {'U_k':>12} | {'V_k':>12}")
print("  " + "-" * 33)
print(f"  {1:>3} | {Uk[0]:>12.6f} | {Vk[0]:>12.6f}")

for k in range(1, N):
    denom = ak[k] * Uk[k-1] + bk[k]
    Uk[k] = -ck[k] / denom
    Vk[k] = (dk[k] - ak[k] * Vk[k-1]) / denom
    print(f"  {k+1:>3} | {Uk[k]:>12.6f} | {Vk[k]:>12.6f}")

# Обратный ход
ys = [0.0] * N
ys[N-1] = Vk[N-1]          # т.к. U_{N-1} = 0

print(f"\nОбратный ход прогонки:")
print(f"  y_{N} = V_{N} = {ys[N-1]:.6f}")

for k in range(N - 2, -1, -1):
    ys[k] = Uk[k] * ys[k+1] + Vk[k]
    print(f"  y_{k+1} = U_{k+1}·y_{k+2} + V_{k+1} = "
          f"{Uk[k]:.6f}·{ys[k+1]:.6f} + {Vk[k]:.6f} = {ys[k]:.6f}")

# ---------------------------------------------------------------
# Итоговая таблица
# ---------------------------------------------------------------
print("\n" + "=" * 40)
print("  Результат (сеточная функция):")
print("=" * 40)
print(f"  {'x_k':>6} | {'y_k':>12}")
print("  " + "-" * 22)
for k in range(N):
    print(f"  {xs[k]:>6.2f} | {ys[k]:>12.6f}")
print("=" * 40)

# ---------------------------------------------------------------
# Проверка: подставляем обратно в аппроксимированные уравнения
# ---------------------------------------------------------------
print("\nПроверка (невязки):")
# Краевое левое
res0 = (-ys[0] + ys[1]) / h
print(f"  y'(0.6) ≈ (y2-y1)/h = {res0:.6f}  (должно быть 0.6)")
# Краевое правое
res3 = (ys[3] - ys[2]) / h
print(f"  y'(0.9) ≈ (y4-y3)/h = {res3:.6f}  (должно быть 1.5)")
# Внутренние уравнения
for k in range(1, N - 1):
    xk = xs[k]
    lhs = ((ys[k+1] - 2*ys[k] + ys[k-1]) / h**2
           + p(xk) * (ys[k+1] - ys[k-1]) / (2*h)
           + q(xk) * ys[k])
    print(f"  ОДУ при x={xk:.1f}: LHS={lhs:.6f}, RHS={f(xk):.6f}, "
          f"невязка={abs(lhs - f(xk)):.2e}")
